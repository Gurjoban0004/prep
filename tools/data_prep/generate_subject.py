#!/usr/bin/env python3
"""
Builds IOT/<subject>-data.js from tools/data_prep/subjects/<subject>/.

Each section module (st1.py, st2.py, end.py, lab.py, cheat.py) exports TOPICS, a list of
{title, subtitle, html}; mcq.py exports MCQ_BANK. The JS globals are
<SUBJECT>_STUDY_DATA and <SUBJECT>_MCQ_BANK, which app.js hydrates by subject id.

Run:  python3 tools/data_prep/generate_subject.py algo aiml sysdesign aptitude
"""

import importlib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))

# section id in app.js CONFIG  ->  module name inside subjects/<id>/
SECTION_MODULES = {"st1": "st1", "st2": "st2", "endTerm": "end", "lab": "lab", "cheatSheet": "cheat"}


def build(subject):
    data = {}
    for section, module in SECTION_MODULES.items():
        try:
            mod = importlib.import_module(f"subjects.{subject}.{module}")
        except ModuleNotFoundError as e:
            if e.name == f"subjects.{subject}.{module}":
                continue
            raise
        data[section] = mod.TOPICS

    bank = importlib.import_module(f"subjects.{subject}.mcq").MCQ_BANK

    ids = [q["id"] for unit in bank for q in unit["questions"]]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise SystemExit(f"{subject}: duplicate MCQ ids {dupes}")
    for unit in bank:
        for q in unit["questions"]:
            if q["correct"] not in q["options"]:
                raise SystemExit(f"{subject}: question {q['id']} has no option {q['correct']}")
    for section, topics in data.items():
        for t in topics:
            missing = {"title", "html"} - t.keys()
            if missing:
                raise SystemExit(f"{subject}.{section}: topic missing {missing}")
            # A bare $ would be picked up by KaTeX's inline math delimiter.
            prose = re.sub(r"<(pre|code)[^>]*>.*?</\1>", "", t["html"], flags=re.S)
            if re.search(r"(?<!\\)\$", prose):
                raise SystemExit(f"{subject}.{section}: stray $ in '{t['title']}'")
            if "foundationsHtml" in t:
                fprose = re.sub(r"<(pre|code)[^>]*>.*?</\1>", "", t["foundationsHtml"], flags=re.S)
                if re.search(r"(?<!\\)\$", fprose):
                    raise SystemExit(f"{subject}.{section}: stray $ in foundations '{t['title']}'")

    prefix = subject.upper()
    target = ROOT / "IOT" / f"{subject}-data.js"
    target.write_text(
        f"// Generated by tools/data_prep/generate_subject.py from tools/data_prep/subjects/{subject}/.\n"
        "// Edit the Python sources and re-run the generator, not this file.\n\n"
        f"const {prefix}_STUDY_DATA = {json.dumps(data, indent=1, ensure_ascii=False)};\n\n"
        f"const {prefix}_MCQ_BANK = {json.dumps(bank, indent=1, ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    counts = " | ".join(f"{k}: {len(v)}" for k, v in data.items())
    print(f"{target.name}: {counts} | questions: {len(ids)} in {len(bank)} quizzes")


if __name__ == "__main__":
    for subject in sys.argv[1:] or ["algo", "aiml", "sysdesign", "aptitude"]:
        build(subject)
